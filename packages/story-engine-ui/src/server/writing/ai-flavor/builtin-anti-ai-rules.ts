/** writerClient 拼接正文请求 messages 时返回的单条消息（与 OpenAI chat 兼容）。 */
export interface WriterChatMessage {
  readonly role: "system" | "user";
  readonly content: string;
}

/**
 * 把引擎产出的正文 prompt（user 段）拼成最终发给模型的 messages：
 *   [ 内置去AI味铁律 (system·固定常量前缀) , 正文 prompt (user) ]
 * 纯函数：system 段恒为 BUILTIN_ANTI_AI_RULES（不依赖 userPrompt），保证 prompt-cache 前缀稳定、可单测。
 */
export function buildFastDraftMessages(userPrompt: string): readonly WriterChatMessage[] {
  return [
    { role: "system", content: BUILTIN_ANTI_AI_RULES },
    { role: "user", content: userPrompt },
  ];
}
